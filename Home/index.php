        <h3>ইতিহাস</h3>
        <p>
            ১৯৩৪ সালের ১লা জানুয়ারী  তৎকালীন বৃহত্তর ফরিদপুর জেলার বর্তমান মাদারীপুর জেলার শিবচর উপজেলার দত্তপাড়া ইউনিয়নএর চৌধুরী শামসুদ্দিন আহমেদ (বাদশা মিয়া) তৎকালীন বৃহত্তর ফরিদপুর জেলার চেয়ারম্যান বিশিষ্ট সমাজসেবক,শিক্ষানুরাগী তার নিজস্ব জায়গায়  শিক্ষার আলো বিস্তারে সর্ব সন্মতিক্রমে "দত্তপাড়া টি.এন একাডেমী" নামে একটি বিদ্যালয় স্থাপনের সিদ্ধান্ত গ্রহণ করেন।দত্তপাড়া টি.এন একাডেমী এর  ক্লাস আরম্ভ হয় ১৯৩৫ সালের পহেলা জানুয়ারি।সেই সময় থেকেই বিদ্যালয়টি সুনামের সাথে শিক্ষার আলো বিতরণ করে চলেছে। বিদ্যালয়টিকে যে মহান ব্যক্তিগণ জমি/জায়গা দান করেছে সময়ের পরিক্রমায় আজ তিনি শুধুই অতীত। আমরা তাকে স্মরণ করি বিনম্র শ্রদ্ধায়।    
            দত্তপাড়া টি.এন একাডেমী এর সাবেক শিক্ষার্থীগণ চিকিৎসক, প্রকৌশলী, আইনবিদ, কৃষিবিদ সহ বাংলাদেশের সরকারি-বেসরকারি বিভিন্ন গুরুত্বপূর্ণ পদে সমাসীন রয়েছেন। রাজনীতিতেও রয়েছে তাদের গুরুত্বপূর্ণ অবদান। আমরা বিশ্বাস করি আমাদের শিক্ষার্থীরা ভবিষ্যতেও বিদ্যালয়ের সুনাম অক্ষুণ্ণ রেখে সমাজ কে আলোকিত করে যাবে।
        </p>
    </article>
